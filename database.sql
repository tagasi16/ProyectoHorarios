CREATE DATABASE IF NOT EXISTS unisimon_lab
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE unisimon_lab;

-- ── Administradores ────────────────────────────
CREATE TABLE IF NOT EXISTS admins (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  username   VARCHAR(50)  NOT NULL UNIQUE,
  password   VARCHAR(255) NOT NULL,
  nombre     VARCHAR(100),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ── Laboratorios ────────────────────────────────
CREATE TABLE IF NOT EXISTS laboratorios (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL,
  ubicacion   VARCHAR(150) DEFAULT '',
  capacidad   INT          DEFAULT 0,
  descripcion VARCHAR(500) DEFAULT '',
  activo      TINYINT(1)   DEFAULT 1,
  created_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ── Grupos académicos ───────────────────────────
CREATE TABLE IF NOT EXISTS grupos (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  nombre     VARCHAR(150) NOT NULL,
  docente    VARCHAR(150) DEFAULT '',
  materia    VARCHAR(150) DEFAULT '',
  color      VARCHAR(7)   DEFAULT '#006633',
  created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ── Horarios (fecha exacta, no día de semana) ───
CREATE TABLE IF NOT EXISTS horarios (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  laboratorio_id INT  NOT NULL,
  grupo_id       INT  NOT NULL,
  dia_semana     INT NOT NULL COMMENT '1=Lun, 2=Mar, 3=Mie, 4=Jue, 5=Vie, 6=Sab, 7=Dom',
  hora_inicio    TIME NOT NULL,
  hora_fin       TIME NOT NULL,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (laboratorio_id) REFERENCES laboratorios(id) ON DELETE CASCADE,
  FOREIGN KEY (grupo_id)       REFERENCES grupos(id)       ON DELETE CASCADE
);

